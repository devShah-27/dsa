// Problem:
// Given a singly linked list where each node represents a digit of a positive integer, add 1 to the number represented by the linked list and return the updated linked list.
// The digits are stored from the most significant digit to the least significant digit.

#include <bits/stdc++.h>
using namespace std;

struct ListNode
{
    int val;
    ListNode *next;
    ListNode()
    {
        val = 0;
        next = NULL;
    }
    ListNode(int data1)
    {
        val = data1;
        next = NULL;
    }
    ListNode(int data1, ListNode *next1)
    {
        val = data1;
        next = next1;
    }
};

void printList(ListNode *head)
{
    while (head != NULL)
    {
        cout << head->val << " ";
        head = head->next;
    }
    cout << endl;
}

ListNode *reverseLL(ListNode *head)
{
    if (!head || !head->next)
        return head;

    ListNode *temp = head, *prev = nullptr;

    while (temp)
    {
        ListNode *front = temp->next;
        temp->next = prev;
        prev = temp;
        temp = front;
    }

    return prev;
}

