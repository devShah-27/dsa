/*
==================================================
OPTIMAL APPROACH (RECURSION)

Idea:
Use recursion to reach the last node and add 1 from right to left.
Each recursive call returns the carry generated by the next digit.
If a final carry remains after processing the head node, create a new node.

Time Complexity: O(N)
Space Complexity: O(N) due to recursion stack
==================================================
*/

int recursiveAddOne(ListNode *head)
{
    if (!head)
        return 1;

    int sum = head->val + recursiveAddOne(head->next);

    head->val = sum % 10;

    return sum / 10;
}

ListNode *addOne(ListNode *head)
{
    if (!head)
        return head;

    int finalCarry = recursiveAddOne(head);

    return finalCarry ? new ListNode(finalCarry, head) : head;
}

int main()
{
    ListNode *head1 = new ListNode(1);
    head1->next = new ListNode(3);
    head1->next->next = new ListNode(4);

    head1 = addOne(head1);
    cout << "Result after adding one: ";
    printList(head1);

    return 0;
}